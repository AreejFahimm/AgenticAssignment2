"""Generate docs/TOOLS.md from the live MCP servers (so the doc can never drift from the code)."""
import asyncio
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from mcp.shared.memory import create_connected_server_and_client_session as connect  # noqa: E402

from mcp_servers.marketplace import server as market  # noqa: E402
from mcp_servers.portfolio import server as portfolio  # noqa: E402
from mcp_servers.workspace import server as workspace  # noqa: E402

AUTH = {"portfolio": "none (local stdio) / network-isolated in compose",
        "marketplace": "Bearer token on the HTTP endpoint (MARKETPLACE_MCP_TOKENS), per-user rate limit, audit log",
        "workspace": "none (local mock; Google OAuth when backed by Calendar/Gmail)"}
OWNER = {"portfolio": "Portfolio MCP (mine)", "marketplace": "Marketplace MCP (mine, wraps the marketplace port)", "workspace": "Workspace MCP (mine)"}


async def main() -> str:
    rows = []
    for name, srv in (("portfolio", portfolio.mcp), ("marketplace", market.mcp), ("workspace", workspace.mcp)):
        async with connect(srv._mcp_server) as c:
            for t in (await c.list_tools()).tools:
                a = t.annotations
                rw = "read" if a and a.readOnlyHint else "write"
                ann = f"readOnly={a.readOnlyHint}, destructive={a.destructiveHint}, idempotent={a.idempotentHint}" if a else "-"
                rows.append(f"| `{t.name}` | {name} | {rw} | {ann} | {AUTH[name]} |")
    third = [
        "| `upwork.*` (official Upwork MCP server, `https://mcp.upwork.com/mcp`) | third-party | read + draft writes | per server | OAuth 2.1, tokens encrypted per user |",
        "| `github.*` (official GitHub MCP server) | third-party | read (repo ingestion) | read-only token | fine-grained PAT, read scope |",
    ]
    return "\n".join(rows + third)


table = asyncio.run(main())
doc = f"""# Tool catalogue (generated by scripts/gen_tools_doc.py)

One row per tool: name, server, read or write, annotations, auth. Agents only see the tools on their allowlist
(`agent/mcp_client.py::ALLOWLIST`); a denied call raises `ToolDenied` and is tested.

| Tool | Server | Read/Write | Annotations | Auth |
|---|---|---|---|---|
{table}

## Third-party servers and why they are trusted (A5)
- **Official Upwork MCP server** (written and operated by Upwork): the only sanctioned automation path to Upwork; every write is a draft the
  user confirms on Upwork. Used through the same marketplace port as GigSim, so the graph cannot tell the difference. **Status: adapter wiring documented,
  NOT exercised here (needs Upwork OAuth credentials); live mode was not run.**
- **GitHub MCP server** (maintained by GitHub): reads repositories the user owns to ingest READMEs and code for the Portfolio index; read-only, scoped
  token, no write tools are on any agent allowlist. **Status: ingestion path documented; the corpora used for results are local synthetic repos.**

## Ownership and tests
Every tool above has a Pydantic input schema, a declared output schema, annotations and tests in `tests/unit/test_mcp_servers.py`; the
schema snapshot in `tests/contract/snapshots/tools.json` fails CI when a signature changes unintentionally.

## Write-tool safety (marketplace)
`create_proposal_draft`, `submit_proposal`, `send_message` take an idempotency key (retries never repeat the effect), support
`dry_run=true` (exact payload and Connects cost, nothing sent), and are only reachable by the approval-gated `submitter` / `messenger`
roles after a LangGraph `interrupt()` returns an approval. Every call lands in an append-only audit log with user, tool, arguments (PII masked), result and trace id.
"""
Path(__file__).resolve().parents[1].joinpath("docs", "TOOLS.md").write_text(doc, encoding="utf-8")
print("wrote docs/TOOLS.md")
